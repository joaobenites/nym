"""training/install_ollama.py: o Modelfile novo mantém o formato do modelo base e só troca o FROM."""
import importlib.util
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def load(name):
    spec = importlib.util.spec_from_file_location(name, ROOT / "training" / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


class InstallTests(unittest.TestCase):
    def test_modelfile_keeps_template_and_params(self):
        inst = load("install_ollama")
        base = ('# Modelfile generated by "ollama show"\nFROM C:\\ollama\\blobs\\sha256-abc\nFROM C:\\ollama\\blobs\\sha256-proj\n'
                'TEMPLATE """{{ .Prompt }}"""\nPARAMETER stop <turn|>\nPARAMETER temperature 1')
        with tempfile.TemporaryDirectory() as d:
            g = Path(d) / "nym.Q4_K_M.gguf"
            g.write_bytes(b"x")
            out = inst.modelfile_from(base, g)
        self.assertEqual(out.count("FROM "), 1)
        self.assertIn(f"FROM {g.resolve()}", out)
        self.assertIn('TEMPLATE """{{ .Prompt }}"""', out)
        self.assertIn("PARAMETER stop <turn|>", out)

    def test_biggest_gguf_is_the_model(self):
        inst = load("install_ollama")
        with tempfile.TemporaryDirectory() as d:
            (Path(d) / "mmproj.gguf").write_bytes(b"x" * 10)
            (Path(d) / "model-Q4_K_M.gguf").write_bytes(b"x" * 100)
            self.assertEqual(inst.find_gguf(Path(d)).name, "model-Q4_K_M.gguf")
            with self.assertRaises(SystemExit):
                inst.find_gguf(Path(d) / "vazia")

    def test_train_script_loads_without_the_training_environment(self):
        train = load("train_lora")          # importar não exige torch/unsloth (só main() exige)
        self.assertTrue(callable(train.main))


class MergedFallbackTests(unittest.TestCase):
    def test_merged_folder_goes_to_ollama_with_quantize(self):
        inst = load("install_ollama")
        with tempfile.TemporaryDirectory() as d:
            (Path(d) / "config.json").write_text("{}")
            src, quantize = inst.find_source(Path(d))
            self.assertEqual((src, quantize), (Path(d), True))
            (Path(d) / "m.gguf").write_bytes(b"x")
            self.assertEqual(inst.find_source(Path(d))[1], False)


class BigGgufTests(unittest.TestCase):
    def test_16bit_gguf_gets_quantized(self):
        inst = load("install_ollama")
        with tempfile.TemporaryDirectory() as d:
            (Path(d) / "model-f16.gguf").write_bytes(b"x" * 100)
            old, inst.BIG_GGUF = inst.BIG_GGUF, 50
            try:
                self.assertTrue(inst.find_source(Path(d))[1])
            finally:
                inst.BIG_GGUF = old
